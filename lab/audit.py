def check_no_emails(paths) -> dict:
    import re as _re
    pattern = _re.compile(r"[\w.+-]+@[\w-]+\.[\w.]{2,}")
    hits = []
    for path in auditable(paths):
        if str(path).startswith("docs/competition_specification"):
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        for number, line in enumerate(text.splitlines(), 1):
            if "noreply" in line or "@example" in line:
                continue
            if pattern.search(line):
                hits.append(f"{path}:{number}")
    return {"ok": not hits,
            "evidence": hits[:3] or "no participant email address published"}


def check_tree_clean(paths) -> dict:
    lines = [line for line in _sh("git", "status", "--porcelain").splitlines()
             if line.strip()]
    # The report is this command's output. Counting a prior generation as a
    # dirty input makes pass two disagree with pass one and prevents a fixed
    # point even when no source changed.
    dirty = [line for line in lines if line[3:] != str(OUT)]
    return {"ok": not dirty, "evidence": dirty[:5] or "clean"}


# What the clean-checkout verification actually verifies. A commit that touches
# only documentation cannot invalidate it -- and no document can contain the
# hash of the commit that contains it, so requiring an exact match would be a
# check nothing could ever pass.
VERIFIED_TREES = ("starter/", "evaluator/", "tests/", "demo/", "lab/",
                  "requirements.txt", "requirements-semantic.txt")


def check_verification_current(paths) -> dict:
    report = json.loads(Path("docs/FINAL_VERIFICATION.md.json").read_text())
    head = _sh("git", "rev-parse", "HEAD").strip()
    at = report.get("commit", "")
    if not report.get("ok"):
        return {"ok": False, "evidence": f"the recorded run FAILED at {at[:7]}"}
    if at == head:
        return {"ok": True, "evidence": f"PASS at {at[:7]}, which is HEAD"}
    moved = _sh("git", "diff", "--name-only", at, "HEAD", "--",
                *VERIFIED_TREES).strip()
    if moved:
        return {"ok": False,
                "evidence": f"verified at {at[:7]}, but code changed since: "
                            + ", ".join(moved.splitlines()[:4])
                            + " — re-run lab.verify_clean"}
    # The current HEAD hash is NOT quoted: this line is written into a file that
    # the next commit changes, so naming HEAD would make it wrong on commit.
    return {"ok": True,
            "evidence": f"PASS at {at[:7]}; only documentation has changed "
                        f"since, so the verified code is unchanged"}


