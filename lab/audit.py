def check_model_assets(paths) -> dict:
    import hashlib
    digests = json.loads(Path("lab/r0/artifacts/digests.json").read_text())
    entry = digests["cross-encoder/ms-marco-TinyBERT-L2-v2"]
    root = Path("lab/r0/artifacts/ms-marco-TinyBERT-L2-v2")
    problems = []
    for name, expected in entry["sha256"].items():
        path = root / name
        if not path.exists():
            problems.append(f"{name} missing")
        elif hashlib.sha256(path.read_bytes()).hexdigest() != expected:
            problems.append(f"{name} sha256 mismatch")
    if not (root / "LICENSE").exists():
        problems.append("LICENSE missing")
    manifest = json.loads(Path("lab/r0/artifacts/manifest.json").read_text())
    if manifest["cross-encoder/ms-marco-TinyBERT-L2-v2"]["license"] != "apache-2.0":
        problems.append("license is not recorded as apache-2.0")
    # Any other model directory would be an unaudited asset.
    others = [str(p) for p in Path("lab/r0/artifacts").iterdir()
              if p.is_dir() and p.name != root.name]
    problems += [f"unaudited model directory {o}" for o in others]
    return {"ok": not problems,
            "evidence": problems or
            f"1 model asset, apache-2.0, revision {entry['revision']}, "
            f"{len(entry['sha256'])} files sha256-verified"}


